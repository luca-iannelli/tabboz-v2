"""Build native Win32 resources from the upstream, editable resource sources."""
from pathlib import Path
import json
import re
import sys

CONTROL = re.compile(r'^\s*CONTROL (.+), (-?\d+), ("[^"]+"|\w+), (.*), (-?\d+), (-?\d+), (\d+), (\d+)$')

def euro_text(text):
    text = text.replace('100000 lire', '50,00 EUR')
    # These parenthesized figures are fixed scooter-part price captions.
    text = re.sub(r'\((\d{1,3}(?:\.\d{3})+)\)', lambda m: '(' + str(int(m[1].replace('.', '')) // 2000) + ',00 EUR)', text)
    return text

def generate(root):
    root = Path(root)
    generate.radio = False
    out = ['// Generated by tools/generate_resources.py; source assets retain upstream GPL.',
           '#pragma code_page(65001)', '#include <windows.h>',
           '5001 RCDATA "assets/splash.png"',
           '1 RT_MANIFEST "native/tabboz.manifest"',
           '1 ICON "assets/app.ico"']
    for path in sorted((root/'resources/icons').glob('*.ico')):
        if path.stem != '1': out.append(f'{path.stem} ICON "resources/icons/{path.name}"')
    for path in sorted((root/'resources/bitmaps').glob('*.bmp')):
        out.append(f'{path.stem} BITMAP "resources/bitmaps/{path.name}"')
    for path in sorted((root/'resources/wavs').glob('*.wav')):
        out.append(f'{int(path.stem[4:])} WAVE "resources/wavs/{path.name}"')
    strings = {}
    for path in sorted((root/'resources/strings').glob('*.json')):
        strings.update(json.loads(path.read_text()))
    out.append('STRINGTABLE\nBEGIN')
    for key, value in sorted(strings.items(), key=lambda kv:int(kv[0])):
        value = euro_text(value).replace('"', '""').replace('\r','').replace('\n', r'\n')
        out.append(f' {key} "{value}"')
    out.append('END')
    menu=(root/'resources/menus/ZARROSIM.rc').read_text()
    for old,new in [('&Special','&Personaggio'),('&Personal Information...','&Dati personali...'),('&Configuration...','&Impostazioni...'),('&Help','&Aiuto'),('&About Tabboz Simulator...','&Informazioni...'),('&Startup Logo','&Schermata iniziale')]:menu=menu.replace(old,new)
    out.append(menu)
    source = (root/'resources/dialogs/dialogs.rc').read_text()
    source = re.sub(r'\\+"', '""', source)
    dialog = None
    for line in source.splitlines():
        match = re.match(r'^(\d+) DIALOG (.*)', line)
        if match:
            dialog = int(match[1])
            generate.radio = False
            if dialog in (1,12,14,15):
                out.append({1:MAIN_DIALOG,12:LOGO_DIALOG,14:CONFIG_DIALOG,15:NEW_GAME_DIALOG}[dialog])
                continue
            x,y,w,h = map(int,match[2].split(','))
            if dialog==10:h+=14
            line = f'{dialog} DIALOGEX 0, 0, {int(w*1.2)+12}, {int(h*1.25)+12}'
        elif dialog in (1,12,14,15):
            continue
        if line.startswith('CLASS '): continue
        line=line.replace('CAPTION "Configuration"','CAPTION "Impostazioni"').replace('Tabboz simulator 32bit','Windows Edition 2.0')
        if line.startswith('FONT '): line = 'FONT 9, "Segoe UI", 400, 0, 1'
        if line.startswith('STYLE '):
            line = 'STYLE DS_SETFONT | DS_MODALFRAME | WS_POPUP | WS_CAPTION | WS_SYSMENU'
        control = CONTROL.match(line)
        if control:
            label, ident, kind, style, x,y,w,h = control.groups()
            number=int(ident); kind=kind.strip('"'); x,y,w,h=map(int,(x,y,w,h))
            if kind=='msctls_progress': kind='msctls_progress32'
            if kind.lower() == 'borshade': continue
            if kind in ('STATIC','BorStatic') and number==1: ident='-1'
            if dialog == 14 and number in (107,109): continue
            label = euro_text(label)
            if kind.lower() == 'borbtn':
                if number in (1,2):
                    kind='BUTTON'; label='"OK"' if number==1 else '"Annulla"'
                    style='WS_CHILD | WS_VISIBLE | WS_TABSTOP | '+('BS_DEFPUSHBUTTON' if number==1 else 'BS_PUSHBUTTON')
                elif (root/f'resources/bitmaps/{number+1000}.bmp').is_file() and w > 20 and h > 20:
                    kind='STATIC'; label='""'; style='WS_CHILD | WS_VISIBLE | SS_OWNERDRAW'
                else:
                    kind='BUTTON'; label='"Nuova partita"' if number==203 else label
                    style='WS_CHILD | WS_VISIBLE | WS_TABSTOP | BS_PUSHBUTTON'
            elif kind.lower() == 'borradio':
                kind='BUTTON'; style='WS_CHILD | WS_VISIBLE | WS_TABSTOP | BS_AUTORADIOBUTTON'
            elif kind.lower() == 'borcheck':
                kind='BUTTON'; style='WS_CHILD | WS_VISIBLE | WS_TABSTOP | BS_AUTOCHECKBOX'
            elif kind.lower() == 'borstatic':
                kind='STATIC'; style='WS_CHILD | WS_VISIBLE | SS_LEFT'
            if dialog == 16 and number in (101,102,110): continue
            if dialog == 16 and kind=='STATIC' and 'computer' in label.lower(): continue
            if dialog == 14:
                label=label.replace('Enable Timer','Eventi mentre il gioco e\' ridotto a icona').replace('Enable Startup Logo','Logo iniziale').replace('Enable Sounds','Suoni')
                if number==203: x,y,w,h=4,153,80,18
                if number==1: x,y,w,h=92,153,33,18
            if kind=='BUTTON' and 'BS_' not in style: style+=' | BS_PUSHBUTTON'
            # Legacy dialogs use a single logical radio choice even when artwork
            # and descriptions occur between options in resource order.
            style=re.sub(r'\s*\|\s*WS_GROUP\b|\bWS_GROUP\s*\|\s*','',style)
            if kind=='BUTTON' and 'RADIOBUTTON' in style:
                if not generate.radio:style+=' | WS_GROUP'
                generate.radio=True
            if kind=='BUTTON' and not ('RADIOBUTTON' in style or 'CHECKBOX' in style): h=max(h,14); w=max(w,38)
            if dialog==10:
                if number in (101,102,103):y=91+(103-number)*14;h=12
                elif y>=129:y+=14
            line=f' CONTROL {label}, {ident}, "{kind}", {style}, {int(x*1.2)+6}, {int(y*1.25)+6}, {int(w*1.2)}, {max(11,int(h*1.25))}'
        out.append(line)
    out.append('''1 VERSIONINFO
FILEVERSION 2,0,0,0
PRODUCTVERSION 2,0,0,0
FILEOS VOS_NT_WINDOWS32
FILETYPE VFT_APP
BEGIN
 BLOCK "StringFileInfo"
 BEGIN
  BLOCK "040904b0"
  BEGIN
   VALUE "FileDescription", "Tabboz Simulator - Windows Edition"
   VALUE "ProductName", "Tabboz Simulator"
   VALUE "FileVersion", "2.0.0"
   VALUE "LegalCopyright", "Original game (C) 1997-2001 Andrea Bonomi and contributors; GPL-3.0-or-later"
  END
 END
 BLOCK "VarFileInfo"
 BEGIN
  VALUE "Translation", 0x409, 1200
 END
END''')
    return '\n'.join(out)+'\n'

